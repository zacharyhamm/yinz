fn coordination_prefixes<'a>(executable: &'a str, session: &'a str) -> Vec<Vec<&'a str>> {
    let mut prefixes = Vec::new();
    for binary in [executable, "yinz"] {
        for explicit_session in [false, true] {
            for command in COORDINATION_COMMANDS {
                let mut prefix = vec![binary];
                if explicit_session {
                    prefix.extend(["--session", session]);
                }
                prefix.extend_from_slice(command);
                prefixes.push(prefix);
            }
        }
    }
    prefixes
}

fn codex_rules(executable: &str, session: &str) -> Result<String> {
    let mut rules = String::from("# Generated by Yinz for this Mother session.\n");
    for prefix in coordination_prefixes(executable, session) {
        let pattern = serde_json::to_string(&prefix).context("serialize Mother command prefix")?;
        rules.push_str(&format!(
            "prefix_rule(pattern={pattern}, decision=\"allow\")\n"
        ));
    }
    Ok(rules)
}

fn claude_args(executable: &str, session: &str) -> Result<Vec<String>> {
    // Shell quoting does not escape Claude's permission-rule delimiters or wildcards.
    for (name, value) in [("executable path", executable), ("session name", session)] {
        if let Some(character) = value
            .chars()
            .find(|c| matches!(c, '(' | ')' | ',' | '*') || c.is_control())
        {
            bail!("Mother cannot scope Claude allow rules to a {name} containing {character:?}");
        }
    }
    let mut args = Vec::new();
    for prefix in coordination_prefixes(executable, session) {
        let command = prefix
            .iter()
            .map(|word| {
                if word
                    .bytes()
                    .all(|b| b.is_ascii_alphanumeric() || b"/._-".contains(&b))
                {
                    (*word).to_owned()
                } else {
                    format!("'{}'", word.replace('\'', "'\\''"))
                }
            })
            .collect::<Vec<_>>()
            .join(" ");
        args.push(format!("--allowedTools=Bash({command}:*)"));
    }
    Ok(args)
}

/// Launch-only permissions; callers must not apply these to ordinary workers.
pub fn coordination_args(kind: &str, work: &Path, session: &str) -> Result<Vec<String>> {
    match kind {
        "claude" => {
            let executable =
                crate::own_binary::server_binary().context("locate Mother session executable")?;
            claude_args(&executable.to_string_lossy(), session)
        },
        "codex" => {
            let work = work.canonicalize().context("resolve Mother directory")?;
            // Codex splits dotted CLI keys literally; a table keeps quotes out of the path key.
            let key = serde_json::to_string(&work).context("serialize Mother trust path")?;
            let mut args = crate::agent::launch::codex_yinz_args().to_vec();
            args.extend([
                "-c".into(),
                format!("projects={{{key}={{trust_level=\"trusted\"}}}}"),
            ]);
            Ok(args)
        },
        _ => Ok(Vec::new()),
    }
}

pub fn replace(path: &Path, bytes: &[u8]) -> Result<()> {
    let parent = path.parent().context("Mother file has no parent")?;
    fs::create_dir_all(parent).context("create Mother file directory")?;
    let mut temp =
        tempfile::NamedTempFile::new_in(parent).context("create Mother temporary file")?;
    temp.write_all(bytes).context("write Mother file")?;
    temp.as_file().sync_all().context("sync Mother file")?;
    temp.persist(path).context("replace Mother file")?;
    fs::File::open(parent)
        .context("open Mother directory")?
        .sync_all()
        .context("sync Mother directory")
}

pub fn provision(work: &Path, session: &str) -> Result<()> {
    for relative in [
        ".agents",
        ".agents/skills",
        ".claude",
        ".claude/skills",
        ".codex",
        ".codex/rules",
    ] {
        if work.join(relative).is_symlink() {
            bail!("Mother instructions directory must not be a symlink: {relative}");
        }
    }
    for (name, content) in [
        ("yinz-mother", SKILL),
        (
            "yinz-agents",
            include_str!("../../assets/skills/yinz-agents/SKILL.md"),
        ),
        (
            "yinz-sessions",
            include_str!("../../assets/skills/yinz-sessions/SKILL.md"),
        ),
    ] {
        for root in [".agents/skills", ".claude/skills"] {
            if work.join(root).join(name).is_symlink() {
                bail!("Mother skill directory must not be a symlink: {name}");
            }
            replace(
                &work.join(root).join(name).join("SKILL.md"),
                content.as_bytes(),
            )?;
        }
    }
    let executable =
        crate::own_binary::server_binary().context("locate Mother session executable")?;
    replace(
        &work.join(".codex/rules/yinz-mother.rules"),
        codex_rules(&executable.to_string_lossy(), session)?.as_bytes(),
    )?;
    let bootstrap = format!("{BOOTSTRAP}\nThe session runs this Yinz executable: {executable:?}. Use this path for commands if `yinz` on PATH is a different version.\n");
    for name in ["AGENTS.md", "CLAUDE.md"] {
        replace(&work.join(name), bootstrap.as_bytes())?;
    }
    Ok(())
}

