use super::*;

#[test]
fn the_template_wires_every_event_it_claims() {
    assert!(
        template_wires_every_event(),
        "PI_HOOK_EVENTS and pi-extension.ts disagree"
    );
    assert!(PI_EXTENSION_TEMPLATE.contains(PI_EXTENSION_MARKER));
}

/// The substitutions the render makes are the ones the template asks for, and none
/// is left behind: a placeholder that survives into the file is an extension pi
/// cannot parse.
#[test]
fn the_render_leaves_no_placeholder_behind() {
    let rendered = render_pi_extension(Path::new("/usr/local/bin/yinz"));
    assert!(rendered.contains("\"/usr/local/bin/yinz\""));
    assert!(rendered.contains(&format!("v{PI_EXTENSION_VERSION} - generated by yinz")));
    assert!(!rendered.contains("__YINZ_BIN__"));
    assert!(!rendered.contains("__TOKEN_ENV__"));
    assert!(!rendered.contains("__VERSION__"));
    // The token name is the broker's own, so the remote route cannot drift from it.
    assert!(rendered.contains(&format!("\"{PANE_TOKEN_ENV}\"")));
}

/// A copy that is already current is left alone, and one that is not is replaced
/// atomically: pi loads the file, and a reader mid-load must see the whole of
/// either version.
#[test]
fn the_data_dir_copy_is_written_only_when_it_differs() {
    let temp = tempfile::tempdir().unwrap();
    let path = temp.path().join("pi/yinz-agent-report.ts");
    assert!(!path.exists());
    write_extension(&path, Path::new("/bin/yinz")).unwrap();
    let first = std::fs::read_to_string(&path).unwrap();
    assert!(first.contains("\"/bin/yinz\""));
    // The temporary is gone: a rename, not a second copy.
    assert_eq!(
        std::fs::read_dir(path.parent().unwrap()).unwrap().count(),
        1
    );
    let written = write_extension(&path, Path::new("/bin/yinz")).unwrap();
    assert_eq!(written, path);
    assert_eq!(std::fs::read_to_string(&path).unwrap(), first);
    write_extension(&path, Path::new("/other/yinz")).unwrap();
    assert!(std::fs::read_to_string(&path)
        .unwrap()
        .contains("/other/yinz"));
}

#[test]
fn a_failed_extension_write_returns_an_error() {
    let temp = tempfile::tempdir().unwrap();
    let parent = temp.path().join("not-a-directory");
    std::fs::write(&parent, "occupied").unwrap();
    assert!(write_extension(&parent.join(PI_EXTENSION_FILE), Path::new("/bin/yinz")).is_err());
    assert_eq!(std::fs::read_to_string(&parent).unwrap(), "occupied");
}

#[test]
fn the_native_generated_path_is_recognizable_without_the_environment() {
    assert!(is_extension_argument(pi_extension_path().to_str().unwrap()));
    assert!(!is_extension_argument("/user/pi/yinz-agent-report.ts"));
}
