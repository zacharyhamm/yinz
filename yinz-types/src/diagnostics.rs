/// A representation of the call stack.
#[derive(Clone, Copy, Serialize, Deserialize, Debug)]
pub struct ErrorContext {
    calls: [ContextType; MAX_THREAD_CALL_STACK],
}

impl ErrorContext {
    /// Returns a new, blank [`ErrorContext`] containing only [`Empty`](ContextType::Empty)
    /// calls.
    pub fn new() -> Self {
        Self {
            calls: [ContextType::Empty; MAX_THREAD_CALL_STACK],
        }
    }

    /// Returns `true` if the calls has all [`Empty`](ContextType::Empty) calls.
    pub fn is_empty(&self) -> bool {
        self.calls.iter().all(|c| c == &ContextType::Empty)
    }

    pub fn calls(&self) -> &[ContextType] {
        &self.calls
    }

    /// Adds a call to this [`ErrorContext`]'s call stack representation.
    pub fn add_call(&mut self, call: ContextType) {
        for ctx in &mut self.calls {
            if let ContextType::Empty = ctx {
                *ctx = call;
                break;
            }
        }
    }
}

impl Default for ErrorContext {
    fn default() -> Self {
        Self::new()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn context_preserves_its_wire_shape_and_bounded_stack() {
        let mut context = ErrorContext::new();
        assert!(context.is_empty());
        context.add_call(ContextType::Screen(ScreenContext::Render));
        let json = r#"{"calls":[{"Screen":"Render"},"Empty","Empty","Empty","Empty","Empty"]}"#;
        assert_eq!(serde_json::to_string(&context).unwrap(), json);
        let decoded: ErrorContext = serde_json::from_str(json).unwrap();
        assert_eq!(decoded.calls(), context.calls());
        for _ in 0..10 {
            context.add_call(ContextType::AsyncTask);
        }
        assert_eq!(context.calls().len(), 6);
        assert_eq!(
            context.calls()[0],
            ContextType::Screen(ScreenContext::Render)
        );
        assert!(context.calls()[1..]
            .iter()
            .all(|c| *c == ContextType::AsyncTask));
    }
}
