#!/usr/bin/env python3
"""Generate the splash SVG and Rust contours with Python 3, pycairo, fontconfig.

Run from any directory. Requires the unmodified Noto Sans Bold Italic face.
The runtime embeds contours, so neither fonts nor Python are needed to run Yinz.
"""

from pathlib import Path
import subprocess

import cairo


ROOT = Path(__file__).resolve().parents[2]


def rust_float(value: float) -> str:
    text = f"{value:.7g}"
    return text if "." in text or "e" in text else text + ".0"


match = subprocess.check_output(
    ["fc-match", "-f", "%{family}\n%{style}\n", "Noto Sans:style=Bold Italic"],
    text=True,
).splitlines()
if match != ["Noto Sans", "Bold Italic"]:
    raise RuntimeError(f"Install Noto Sans Bold Italic; fontconfig returned {match}")

ctx = cairo.Context(cairo.ImageSurface(cairo.FORMAT_ARGB32, 1, 1))
ctx.select_font_face("Noto Sans", cairo.FONT_SLANT_ITALIC, cairo.FONT_WEIGHT_BOLD)
ctx.set_font_size(1000)
options = cairo.FontOptions()
options.set_hint_style(cairo.HINT_STYLE_NONE)
options.set_hint_metrics(cairo.HINT_METRICS_OFF)
ctx.set_font_options(options)
glyphs, _, _ = ctx.get_scaled_font().text_to_glyphs(0, 0, "yinz")
ctx.glyph_path(glyphs)
left, top, right, bottom = ctx.path_extents()
scale = 2 / (bottom - top)
word_center = (left + right) / 2
middle = (top + bottom) / 2
svg = [
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="'
    f'{left - 40:g} {top - 40:g} {right - left + 80:g} {bottom - top + 80:g}" '
    'role="img" aria-labelledby="title">',
    '  <title id="title">yinz — Noto Sans Bold Italic</title>',
    '  <desc>Outlines from Noto Sans Bold Italic. Font copyright 2022 The Noto Project Authors; SIL Open Font License 1.1.</desc>',
]
rust = [
    "// Generated by assets/splash/generate.py; do not edit by hand.",
    "// Coordinates use the word's visible height = 2, with y increasing downward.",
    "use super::geometry::Outline;",
    "#[rustfmt::skip]",
    "pub(super) const OUTLINES: [Outline; 4] = [",
]
for letter, glyph in zip("yinz", glyphs, strict=True):
    ctx.new_path()
    ctx.glyph_path([glyph])
    x0, _, x1, _ = ctx.path_extents()
    center = (x0 + x1) / 2
    commands = []
    for kind, coords in ctx.copy_path():
        commands.append(
            {cairo.PATH_MOVE_TO: "M", cairo.PATH_LINE_TO: "L",
             cairo.PATH_CURVE_TO: "C", cairo.PATH_CLOSE_PATH: "Z"}[kind]
            + " ".join(f"{c:g}" for c in coords)
        )
    svg.append(f'  <path id="{letter}" d="{" ".join(commands)}"/>')
    # Cairo flattens the very same outlines used in the SVG to sub-dot precision.
    ctx.set_tolerance(0.5)
    segments = []
    for kind, coords in ctx.copy_path_flat():
        if kind == cairo.PATH_MOVE_TO:
            previous = start = coords
            continue
        point = start if kind == cairo.PATH_CLOSE_PATH else coords
        if point != previous:
            segments.append((previous, point))
        previous = point
    rust.append(f"    Outline {{ center: {rust_float((center - word_center) * scale)}, segments: &[")
    for a, b in segments:
        values = [(a[0] - center) * scale, (a[1] - middle) * scale,
                  (b[0] - center) * scale, (b[1] - middle) * scale]
        rust.append("        [" + ", ".join(rust_float(v) for v in values) + "],")
    rust.append("    ] },")
svg.append("</svg>\n")
rust.append("];")
(ROOT / "assets/splash/yinz-noto-sans-bold-italic.svg").write_text("\n".join(svg))
(ROOT / "yinz-client/src/splash/outlines.rs").write_text("\n".join(rust) + "\n")
