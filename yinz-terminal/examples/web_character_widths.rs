//! Rebuild the width table shipped with the web terminal after updating unicode-width.
use unicode_width::UnicodeWidthChar;

fn main() {
    println!("// Generated by cargo run -q -p yinz-terminal --example web_character_widths");
    println!("// Inclusive start, inclusive end, and cell width for non-single-width ranges.");
    println!("export const widthRanges = [");
    let mut start = 0;
    let mut previous = 0;
    // One extra iteration flushes the final range.
    for code in 0..=0x110000 {
        let width = char::from_u32(code).map_or(1, |c| c.width().unwrap_or(0));
        if width != previous {
            if previous != 1 {
                println!("  [0x{start:x}, 0x{:x}, {previous}],", code - 1);
            }
            start = code;
            previous = width;
        }
    }
    println!("];");
}
