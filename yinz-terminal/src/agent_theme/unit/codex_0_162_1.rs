use super::*;
use std::collections::BTreeMap;

fn snapshot() -> AgentThemeSnapshot {
    AgentThemeSnapshot {
        version: SNAPSHOT_VERSION,
        provider: "codex".into(),
        provider_version: "0.162.1".into(),
        theme: "automatic".into(),
        provenance: vec![],
        availability: Availability::Partial("automatic syntax unresolved".into()),
        definitions: vec![],
        collisions: vec![],
    }
}

struct Fixture {
    name: String,
    indexed: bool,
    foreground: Rgb,
    background: Rgb,
    colors: BTreeMap<String, SourceColor>,
}

#[test]
fn matches_pinned_provider_fixtures() {
    // Generated by executing the unmodified rust-v0.162.1 style.rs, color.rs,
    // style/contrast.rs and terminal_palette.rs color search/table against a tiny
    // ratatui Style/Color shim, with the terminal probe supplied these samples.
    // Includes contrast correction, light/dark threshold, tinted surfaces, and
    // selection's alternate-fill branch. Expectations do not call our derivations.
    let fixtures: Vec<serde_json::Value> =
        serde_json::from_str(include_str!("codex-0.162.1-colors.json")).unwrap();
    for value in fixtures {
        let fixture = Fixture {
            name: value["name"].as_str().unwrap().into(),
            indexed: value["indexed"].as_bool().unwrap(),
            foreground: serde_json::from_value(value["foreground"].clone()).unwrap(),
            background: serde_json::from_value(value["background"].clone()).unwrap(),
            colors: serde_json::from_value(value["colors"].clone()).unwrap(),
        };
        let mut snapshot = snapshot();
        assert!(observe(&mut snapshot, 10, fixture.foreground));
        assert!(observe(&mut snapshot, 11, fixture.background));
        for (name, expected) in &fixture.colors {
            if name.starts_with("footer") {
                continue;
            }
            let token = if name.ends_with("-accent") {
                "surface-accent"
            } else {
                name
            };
            let pair_bg = match name.as_str() {
                "composer-accent" => fixture.colors.get("composer-plan"),
                "history-accent" => fixture.colors.get("history-prompt"),
                "selection.secondary" => fixture.colors.get("selection.background"),
                _ => None,
            };
            assert!(
                snapshot.definitions.iter().any(|d| {
                    d.token == format!("codex.terminal.{token}")
                        && d.color == *expected
                        && pair_bg.is_none_or(|bg| d.pair == Some((*expected, *bg)))
                }),
                "{} indexed={}: {name} expected {expected:?}",
                fixture.name,
                fixture.indexed
            );
        }
    }
}

#[test]
fn footer_matches_provider_softening_contrast_and_indexed_fixtures() {
    let fixtures: Vec<serde_json::Value> =
        serde_json::from_str(include_str!("codex-0.162.1-colors.json")).unwrap();
    for fixture in fixtures {
        let colors: BTreeMap<String, SourceColor> =
            serde_json::from_value(fixture["colors"].clone()).unwrap();
        for palette in ["mocha", "latte", "custom"] {
            // A custom theme can itself be named "automatic"; selected candidates still win.
            let mut snapshot = snapshot();
            for item in ["model", "path"] {
                snapshot.definitions.push(Definition {
                    token: format!("codex.footer.selected.{item}"),
                    channel: Channel::Foreground,
                    color: colors[&format!("footer-source.{palette}.{item}")],
                    pair: None,
                    target: None,
                });
            }
            observe(
                &mut snapshot,
                10,
                serde_json::from_value(fixture["foreground"].clone()).unwrap(),
            );
            observe(
                &mut snapshot,
                11,
                serde_json::from_value(fixture["background"].clone()).unwrap(),
            );
            for (item, role) in [("model", Role::Accent), ("path", Role::Success)] {
                let expected = colors[&format!("footer.{palette}.{item}")];
                assert!(
                    snapshot.definitions.iter().any(|d| {
                        d.token == format!("codex.footer.selected.{item}")
                            && d.color == expected
                            && d.pair == Some((expected, SourceColor::Default))
                            && d.target == Some(role.into())
                    }),
                    "{palette}.{item}: {fixture}"
                );
            }
            if palette == "mocha" && fixture["name"] == "light" && fixture["indexed"] == true {
                // ANSI reduction makes the model and separator identical; keep collision priority.
                let key = yinz_types::agent::theme::MatchKey {
                    channel: Channel::Foreground,
                    color: SourceColor::Index(243),
                    pair: Some((SourceColor::Index(243), SourceColor::Default)),
                };
                assert_eq!(snapshot.compile().0[&key], Some(Role::Muted.into()));
            }
        }
    }
}

#[test]
fn automatic_footer_selects_only_the_startup_palette_and_preserves_ansi_fallbacks() {
    for (background, variant) in [((18, 20, 30), "dark"), ((255, 255, 255), "light")] {
        let mut snapshot = snapshot();
        for (variant, model, path) in [("dark", 6, 2), ("light", 14, 10)] {
            for (item, index) in [("model", model), ("path", path)] {
                snapshot.definitions.push(Definition {
                    token: format!("codex.footer.{variant}.{item}"),
                    channel: Channel::Foreground,
                    color: SourceColor::Index(index),
                    pair: None,
                    target: None,
                });
            }
        }
        observe(&mut snapshot, 11, background);
        assert!(snapshot
            .definitions
            .iter()
            .filter(|d| d.token.starts_with("codex.footer."))
            .all(|d| d.target.is_none()));
        observe(&mut snapshot, 10, (220, 220, 220));
        let mapped: Vec<_> = snapshot
            .definitions
            .iter()
            .filter(|d| d.token.starts_with("codex.footer.") && d.target.is_some())
            .collect();
        assert_eq!(mapped.len(), 4);
        assert!(mapped
            .iter()
            .all(|d| d.token.starts_with(&format!("codex.footer.{variant}."))));
        for d in mapped {
            assert_eq!(d.pair, Some((d.color, SourceColor::Default)));
            assert_eq!(
                d.target,
                Some(
                    if d.token.ends_with("model") {
                        Role::Accent
                    } else {
                        Role::Success
                    }
                    .into()
                )
            );
        }
        let before = snapshot.clone();
        assert!(!observe(&mut snapshot, 11, (130, 130, 130)));
        assert_eq!(before, snapshot);
    }
}

#[test]
fn nightfox_selected_secondary_uses_selection_colors_in_both_color_modes() {
    use crate::agent_theme::Mapping;
    use crate::panes::terminal_character::{AnsiCode, CharacterStyles};
    use yinz_types::{colors::PaletteColor, style::Style};

    let mut snapshot = snapshot();
    observe(&mut snapshot, 10, (205, 206, 207));
    observe(&mut snapshot, 11, (25, 35, 48));
    let mut style = Style::default();
    style.colors.text_selected.base = PaletteColor::Rgb((205, 206, 207));
    style.colors.text_selected.background = PaletteColor::Rgb((41, 57, 79));
    let mapping = Mapping::new(&snapshot, style);
    for (foreground, background) in [
        (
            AnsiCode::RgbCode((57, 59, 62)),
            AnsiCode::RgbCode((99, 168, 248)),
        ),
        (AnsiCode::ColorIndex(237), AnsiCode::ColorIndex(75)),
    ] {
        let mapped = mapping.apply(CharacterStyles {
            foreground: Some(foreground),
            background: Some(background),
            ..crate::panes::terminal_character::DEFAULT_STYLES
        });
        assert_eq!(mapped.foreground, Some(AnsiCode::RgbCode((205, 206, 207))));
        assert_eq!(mapped.background, Some(AnsiCode::RgbCode((41, 57, 79))));
        assert!(ratio((205, 206, 207), (41, 57, 79)) >= 4.5);
    }
}

#[test]
fn requires_both_observations_and_keeps_first_samples_across_serialization() {
    let mut snapshot = snapshot();
    observe(&mut snapshot, 11, (18, 20, 30));
    assert_eq!(snapshot.definitions.len(), 1);
    let json = serde_json::to_string(&snapshot).unwrap();
    let mut snapshot: AgentThemeSnapshot = serde_json::from_str(&json).unwrap();
    assert!(!observe(&mut snapshot, 11, (255, 255, 255)));
    assert!(observe(&mut snapshot, 10, (220, 220, 220)));
    assert!(snapshot
        .definitions
        .iter()
        .any(|d| d.token == "codex.terminal.composer-plan"));
    let before = snapshot.clone();
    assert!(!observe(&mut snapshot, 10, (0, 0, 0)));
    assert_eq!(snapshot, before);
}

#[test]
fn other_providers_and_unavailable_palettes_are_unchanged() {
    for (provider, version, availability) in [
        ("claude", "0.162.1", Availability::Available),
        (
            "codex",
            "0.162.1",
            Availability::Unavailable("unknown theme".into()),
        ),
    ] {
        let mut s = snapshot();
        s.provider = provider.into();
        s.provider_version = version.into();
        s.availability = availability;
        let before = s.clone();
        assert!(!observe(&mut s, 10, (220, 220, 220)));
        assert!(!observe(&mut s, 11, (18, 20, 30)));
        assert_eq!(s, before);
    }
}

#[test]
fn color_replies_match_provider_scaling_and_reject_invalid_or_wrong_channels() {
    for (reply, expected) in [
        ("\x1b]10;rgb:f/80/1000\x07", (255, 128, 15)),
        ("\x1b]10;RGBA:123/456/789/ffff\x1b\\", (18, 69, 120)),
    ] {
        assert_eq!(parse_reply(10, reply.as_bytes()), Some(expected));
        assert_eq!(parse_reply(11, reply.as_bytes()), None);
    }
    for reply in [
        "",
        "\x1b]10;rgb:/ff/ff\x07",
        "\x1b]10;rgb:ff/ff/fffff\x07",
        "\x1b]10;rgb:gg/00/00\x07",
        "\x1b]10;rgb:+f/00/00\x07",
        "\x1b]10;rgb:ff/ff/ff",
        "\x1b]10;rgb:ff/ff/ff/ff\x07",
        "\x1b]10;#ffffff\x07",
    ] {
        assert_eq!(parse_reply(10, reply.as_bytes()), None, "{reply:?}");
    }
}

#[test]
fn indexed_channels_and_selection_pairs_keep_semantic_roles_and_collision_precedence() {
    use yinz_types::agent::theme::MatchKey;
    let mut snapshot = snapshot();
    observe(&mut snapshot, 10, (220, 220, 220));
    observe(&mut snapshot, 11, (18, 20, 30));
    let (mapping, _) = snapshot.compile();
    for (channel, index, role) in [
        (Channel::Background, 236, Role::Surface),
        (Channel::Background, 237, Role::Surface),
        (Channel::Foreground, 237, Role::Subtle),
        (Channel::Foreground, 245, Role::Muted),
        (Channel::Foreground, 179, Role::Warning),
        (Channel::Foreground, 75, Role::Accent),
    ] {
        assert_eq!(
            mapping[&MatchKey {
                channel,
                color: SourceColor::Index(index),
                pair: (channel == Channel::Foreground)
                    .then_some((SourceColor::Index(index), SourceColor::Default))
            }],
            Some(role.into())
        );
    }
    let pair = Some((SourceColor::Index(232), SourceColor::Index(75)));
    for (channel, index, role) in [
        (Channel::Foreground, 232, Role::SelectionForeground),
        (Channel::Background, 75, Role::SelectionBackground),
    ] {
        assert_eq!(
            mapping[&MatchKey {
                channel,
                color: SourceColor::Index(index),
                pair
            }],
            Some(role.into())
        );
    }
    // The existing explicit theme-accent precedence remains stronger than derived UI roles.
    push(
        &mut snapshot.definitions,
        "codex.accent",
        Channel::Foreground,
        SourceColor::Index(245),
        None,
        Role::Accent,
    );
    let (mapping, collisions) = snapshot.compile();
    assert_eq!(
        mapping[&MatchKey {
            channel: Channel::Foreground,
            color: SourceColor::Index(245),
            pair: None
        }],
        Some(Role::Accent.into())
    );
    assert!(!collisions.is_empty());
}

