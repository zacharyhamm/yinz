//! `zellij hocus hooks` — wiring Claude Code's hooks to the agent plugins.
//!
//! `hocus-agentd` decides whether an agent pane is busy, idle or blocked on the user
//! by reading its screen every five seconds and hashing what it finds, and — for the
//! last of those three — by asking a model about the pane's tail. That is the only
//! thing that works for an agent which says nothing about itself, and it is a guess
//! bought with about fifteen seconds and an HTTP round trip.
//!
//! Claude Code says. This command installs a small script as a Claude Code hook so
//! that a `claude` running in a zellij pane reports its own state, and the daemon
//! stops guessing about that pane. Everything here is local file work: it writes a
//! script and merges some entries into a settings file, and never needs a session.
//!
//! The two halves that must agree with something else are marked where they appear:
//! the pipe's name and its argument, which are `hocus_proto::wire`'s, and the shape
//! of the settings block, which is Claude Code's.

use anyhow::{anyhow, Context, Result};
use serde_json::{json, Map, Value};
use std::path::{Path, PathBuf};

use zellij_utils::cli::{Hocus, HocusHooks};

/// The pipe `hocus-agentd` listens for, and the argument naming the pane.
///
/// Spelled here as well as in `hocus_proto::wire`, because that crate is a wasm
/// plugin's and this binary does not link it. A pipe name that does not match is
/// silent — the host delivers it and nothing answers — so the two spellings are worth
/// a grep: `AGENT_HOOK` and `HOOK_PANE_ID` in `default-plugins/hocus-proto/src/wire.rs`.
const PIPE_NAME: &str = "agent_hook";
const PIPE_PANE_ID_ARG: &str = "pane_id";

/// The Claude Code hook events wired, and what each one buys.
///
/// None of them takes a matcher: every entry fires on every occurrence of its event
/// and the plugin decides what it means. That is deliberate for `Notification`, whose
/// matcher would have to name the notification kinds that mean "blocked on the user" —
/// a list Claude Code adds to between versions, and one already written in
/// `agents::hook_phase` where it can be tested.
const EVENTS: &[&str] = &[
    // The feed begins, and the pane is proved to be running Claude Code.
    "SessionStart",
    // Work starts.
    "UserPromptSubmit",
    // Work continues, and names the tool it is in.
    "PreToolUse",
    "PostToolUse",
    // Blocked on the user, said as the prompt goes up.
    "PermissionRequest",
    // The same, from the other direction: the backstop for a Claude Code too old to
    // have `PermissionRequest`, and the only signal for an MCP form or a background
    // session wanting input.
    "Notification",
    // The turn ended.
    "Stop",
    // The feed ends.
    "SessionEnd",
];

/// Seconds a hook may take before Claude Code abandons it.
///
/// Explicit because the default is ten minutes and a hook blocks the turn: a `zellij
/// pipe` against a socket whose server has gone must not be able to stall an agent.
/// Five rather than one because `SessionEnd` is special-cased at the other end —
/// every `SessionEnd` hook shares a 1.5s budget, raised only to match an individual
/// timeout — and a feed that ends is worth waiting a moment for.
const TIMEOUT_SECONDS: u64 = 5;

/// Bumped whenever [`script`] changes, so `status` can say the installed copy is old.
const SCRIPT_VERSION: u32 = 1;

/// What marks an entry in the settings file as ours, and nothing else as ours.
///
/// Matched against the entry's `command`, so a person who moved the script or wrapped
/// it in something still has their entry replaced rather than duplicated.
const MARKER: &str = "hocus-hook.sh";

pub(crate) fn hocus(command: Hocus) -> Result<()> {
    let Hocus::Hooks(hooks) = command;
    match hooks {
        HocusHooks::Install { project, dry_run } => install(project, dry_run),
        HocusHooks::Uninstall { project } => uninstall(project),
        HocusHooks::Status => status(),
    }
}

/// The script Claude Code runs, with this binary's own path baked in.
///
/// Baked rather than looked up because a hook inherits the environment `claude` was
/// started with, which is not always one where `zellij` is on the path — a desktop
/// launcher, a login shell that sets the path in a file an interactive shell reads.
/// The lookup stays as the fallback for the case the baked path stops existing,
/// which is what an upgrade that moves the binary looks like.
fn script(zellij: &Path) -> String {
    let zellij = zellij.display();
    format!(
        r#"#!/bin/sh
# hocus-hook v{SCRIPT_VERSION} - generated by `zellij hocus hooks install`. Do not edit;
# `zellij hocus hooks install` rewrites this file, and `--uninstall` removes it.
#
# Claude Code runs this on each wired hook event, with that event's JSON on stdin.
# It forwards the JSON to hocus-agentd, which is what lets a Claude pane report its
# own busy/waiting/idle state instead of being guessed at from its screen.
#
# Two rules this file keeps, both of which matter:
#   - it never writes to stdout. On UserPromptSubmit and SessionStart, an exit-0
#     hook's stdout is injected verbatim into Claude's context.
#   - it always exits 0. A hook that fails must not interfere with the agent it is
#     only reporting on.

# Not in a zellij pane, so there is no pane for the daemon to attach this to.
[ -n "$ZELLIJ_PANE_ID" ] || exit 0

ZELLIJ_BIN='{zellij}'
[ -x "$ZELLIJ_BIN" ] || ZELLIJ_BIN=zellij

payload=$(cat)
# Broadcast, deliberately without --plugin: addressing the daemon by url would miss
# the running instance and launch a second one. `--` keeps a payload that starts with
# a dash from being read as a flag.
"$ZELLIJ_BIN" pipe --name {PIPE_NAME} --args "{PIPE_PANE_ID_ARG}=$ZELLIJ_PANE_ID" \
    -- "$payload" >/dev/null 2>&1

exit 0
"#
    )
}

/// One handler entry, as Claude Code's settings spell it.
fn handler(command: &str) -> Value {
    json!({
        "type": "command",
        "command": command,
        "timeout": TIMEOUT_SECONDS,
    })
}

/// Whether one handler entry is one we wrote.
fn is_ours(handler: &Value) -> bool {
    handler
        .get("command")
        .and_then(Value::as_str)
        .is_some_and(|command| command.contains(MARKER))
}

/// `settings` with our entries removed and then added back, for every event we wire.
///
/// Idempotent by construction: the removal runs first, so installing twice leaves one
/// entry per event rather than two. Nothing else in the file is touched — it is parsed
/// as a whole `Value` and handed back with the same keys it arrived with, so a setting
/// this binary has never heard of survives the round trip.
pub(crate) fn install_into(settings: Value, command: &str) -> Value {
    let mut settings = uninstall_from(settings);
    let root = settings
        .as_object_mut()
        .expect("uninstall_from always answers an object");
    let hooks = root
        .entry("hooks")
        .or_insert_with(|| Value::Object(Map::new()));
    if !hooks.is_object() {
        // Someone has written something else under this key. Replacing it would
        // throw their file away, so the entries go nowhere and `status` will say so.
        return settings;
    }
    let hooks = hooks.as_object_mut().expect("checked above");
    for event in EVENTS {
        let groups = hooks
            .entry(*event)
            .or_insert_with(|| Value::Array(Vec::new()));
        if let Some(groups) = groups.as_array_mut() {
            // No `matcher`: an entry without one fires on every occurrence of the
            // event, which is what we want for all eight. See `EVENTS`.
            groups.push(json!({ "hooks": [handler(command)] }));
        }
    }
    settings
}

/// `settings` with every entry of ours removed, and nothing else changed.
///
/// A group we emptied goes with it, so uninstalling does not leave a pile of
/// `{"hooks":[]}` behind; a group that still holds someone else's handler stays, minus
/// ours. An event left with no groups is dropped for the same reason.
pub(crate) fn uninstall_from(mut settings: Value) -> Value {
    if !settings.is_object() {
        // An empty or unparseable file is an empty settings object, not an error: the
        // install below has to work on a machine where nobody has written one yet.
        settings = Value::Object(Map::new());
    }
    let Some(hooks) = settings
        .as_object_mut()
        .expect("made an object above")
        .get_mut("hooks")
        .and_then(Value::as_object_mut)
    else {
        return settings;
    };
    for groups in hooks.values_mut() {
        let Some(groups) = groups.as_array_mut() else {
            continue;
        };
        for group in groups.iter_mut() {
            if let Some(handlers) = group.get_mut("hooks").and_then(Value::as_array_mut) {
                handlers.retain(|handler| !is_ours(handler));
            }
        }
        groups.retain(|group| {
            group
                .get("hooks")
                .and_then(Value::as_array)
                .is_none_or(|handlers| !handlers.is_empty())
        });
    }
    hooks.retain(|_, groups| groups.as_array().is_none_or(|groups| !groups.is_empty()));
    if hooks.is_empty() {
        settings
            .as_object_mut()
            .expect("made an object above")
            .remove("hooks");
    }
    settings
}

/// Which events in a settings document have an entry of ours.
pub(crate) fn installed_events(settings: &Value) -> Vec<String> {
    let Some(hooks) = settings.get("hooks").and_then(Value::as_object) else {
        return Vec::new();
    };
    hooks
        .iter()
        .filter(|(_, groups)| {
            groups
                .as_array()
                .into_iter()
                .flatten()
                .filter_map(|group| group.get("hooks")?.as_array())
                .flatten()
                .any(is_ours)
        })
        .map(|(event, _)| event.clone())
        .collect()
}

fn home() -> Result<PathBuf> {
    std::env::var_os("HOME")
        .map(PathBuf::from)
        .ok_or_else(|| anyhow!("HOME is not set, so there is no ~/.claude to install into"))
}

fn script_path() -> Result<PathBuf> {
    Ok(home()?.join(".claude").join("hocus").join(MARKER))
}

/// Which settings file to write. Claude Code *merges* hooks across the two rather
/// than one overriding the other, which is why installing into both fires everything
/// twice — `status` says so when it sees it.
fn settings_path(project: bool) -> Result<PathBuf> {
    if project {
        return Ok(std::env::current_dir()
            .context("cannot tell which project this is")?
            .join(".claude")
            .join("settings.json"));
    }
    Ok(home()?.join(".claude").join("settings.json"))
}

/// A settings file as a `Value`. A file that is not there is an empty object; one that
/// does not parse is an error, because writing over it would destroy it.
fn read_settings(path: &Path) -> Result<Value> {
    match std::fs::read_to_string(path) {
        Ok(text) if text.trim().is_empty() => Ok(Value::Object(Map::new())),
        Ok(text) => serde_json::from_str(&text)
            .with_context(|| format!("{} is not valid JSON", path.display())),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(Value::Object(Map::new())),
        Err(error) => Err(error).with_context(|| format!("cannot read {}", path.display())),
    }
}

/// Write a settings file, keeping a copy of what was there.
///
/// Through a temporary file in the same folder and a rename, so a crash midway leaves
/// the old file rather than half of the new one. The `.bak` is written first and is
/// what a person reaches for when this got something wrong.
fn write_settings(path: &Path, settings: &Value) -> Result<()> {
    let folder = path
        .parent()
        .ok_or_else(|| anyhow!("{} has no folder to write into", path.display()))?;
    std::fs::create_dir_all(folder)
        .with_context(|| format!("cannot create {}", folder.display()))?;
    if path.exists() {
        let backup = path.with_extension("json.bak");
        std::fs::copy(path, &backup).with_context(|| {
            format!("cannot back {} up to {}", path.display(), backup.display())
        })?;
    }
    let mut text = serde_json::to_string_pretty(settings).context("cannot serialize settings")?;
    text.push('\n');
    let temporary = path.with_extension("json.hocus-tmp");
    std::fs::write(&temporary, &text)
        .with_context(|| format!("cannot write {}", temporary.display()))?;
    std::fs::rename(&temporary, path)
        .with_context(|| format!("cannot replace {}", path.display()))?;
    Ok(())
}

fn install(project: bool, dry_run: bool) -> Result<()> {
    let zellij = std::env::current_exe().context("cannot find this zellij binary")?;
    let script_path = script_path()?;
    let script = script(&zellij);
    let settings_path = settings_path(project)?;
    let settings = read_settings(&settings_path)?;
    let command = script_path.display().to_string();
    let updated = install_into(settings, &command);

    if dry_run {
        println!("would write {}:\n", script_path.display());
        println!("{script}");
        println!(
            "would merge into {} (everything else in it is left as it is):\n",
            settings_path.display()
        );
        println!(
            "{}",
            serde_json::to_string_pretty(updated.get("hooks").unwrap_or(&Value::Null))?
        );
        return Ok(());
    }

    let folder = script_path.parent().expect("the script is in a folder");
    std::fs::create_dir_all(folder)
        .with_context(|| format!("cannot create {}", folder.display()))?;
    std::fs::write(&script_path, &script)
        .with_context(|| format!("cannot write {}", script_path.display()))?;
    make_executable(&script_path)?;
    write_settings(&settings_path, &updated)?;

    println!("wrote {}", script_path.display());
    println!(
        "wired {} events in {}",
        EVENTS.len(),
        settings_path.display()
    );
    println!(
        "kept the previous settings as {}",
        settings_path.with_extension("json.bak").display()
    );
    // Said rather than hidden: the file is re-serialized from a parse, so its keys
    // come back in sorted order. Nothing about the settings changes, but a file under
    // version control will show a diff that is mostly not ours.
    println!("(settings are rewritten from a parse, so key order may change)");
    println!("run `zellij hocus hooks status` to check, or `/hooks` inside Claude Code");
    Ok(())
}

#[cfg(unix)]
fn make_executable(path: &Path) -> Result<()> {
    use std::os::unix::fs::PermissionsExt;
    std::fs::set_permissions(path, std::fs::Permissions::from_mode(0o755))
        .with_context(|| format!("cannot make {} executable", path.display()))
}

fn uninstall(project: bool) -> Result<()> {
    let settings_path = settings_path(project)?;
    let settings = read_settings(&settings_path)?;
    let removed = installed_events(&settings).len();
    write_settings(&settings_path, &uninstall_from(settings))?;
    println!("removed {removed} events from {}", settings_path.display());

    let script_path = script_path()?;
    match std::fs::remove_file(&script_path) {
        Ok(()) => println!("removed {}", script_path.display()),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {},
        Err(error) => {
            return Err(error).with_context(|| format!("cannot remove {}", script_path.display()))
        },
    }
    Ok(())
}

/// What is wired, and the things that would quietly stop it working.
fn status() -> Result<()> {
    let script_path = script_path()?;
    match std::fs::read_to_string(&script_path) {
        Ok(text) if text.contains(&format!("hocus-hook v{SCRIPT_VERSION} ")) => {
            println!("script:  {} (current)", script_path.display());
        },
        Ok(_) => println!(
            "script:  {} (older than this zellij - run `install` again)",
            script_path.display()
        ),
        Err(_) => println!("script:  {} (missing)", script_path.display()),
    }

    let mut wired_anywhere = 0usize;
    for (label, project) in [("user", false), ("project", true)] {
        let heading = format!("{label}:");
        let Ok(path) = settings_path(project) else {
            continue;
        };
        let settings = match read_settings(&path) {
            Ok(settings) => settings,
            Err(error) => {
                println!("{heading:<9}{} ({error:#})", path.display());
                continue;
            },
        };
        let events = installed_events(&settings);
        wired_anywhere += usize::from(!events.is_empty());
        println!(
            "{heading:<9}{} - {} of {} events wired",
            path.display(),
            events.len(),
            EVENTS.len()
        );
        for missing in EVENTS
            .iter()
            .filter(|event| !events.iter().any(|wired| wired == *event))
        {
            if !events.is_empty() {
                println!("            missing: {missing}");
            }
        }
        // The two ways a correctly written hook never runs.
        if settings.get("disableAllHooks") == Some(&Value::Bool(true)) {
            println!("            disableAllHooks is on: nothing here runs");
        }
        if settings.get("allowManagedHooksOnly") == Some(&Value::Bool(true)) {
            println!("            allowManagedHooksOnly is on: nothing here runs");
        }
    }
    if wired_anywhere > 1 {
        println!(
            "note:    wired in both files. Claude Code merges hooks rather than \
             overriding, so every event fires twice"
        );
    }

    match std::env::var("ZELLIJ_PANE_ID") {
        Ok(pane_id) => println!("pane:    this shell is zellij pane {pane_id}"),
        Err(_) => println!(
            "pane:    this shell is not in a zellij pane, so a claude started here \
             would report nothing"
        ),
    }
    Ok(())
}
